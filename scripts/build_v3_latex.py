HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import build_v3_references as B          # REFS, load()  (re-writes references.md identically)

V3 = os.path.join(ROOT, "paper", "v3_ismb"); OUT = os.path.join(V3, "overleaf"); FIG = os.path.join(OUT, "figures")
os.makedirs(FIG, exist_ok=True)

KEY = {"Adebayo et al. 2018": "Adebayo2018", "Bai et al. 2023": "Bai2023", "Davis et al. 2011": "Davis2011", "DeYoung et al. 2020": "DeYoung2020",
       "Huang et al. 2021": "Huang2021", "Jacovi and Goldberg 2020": "Jacovi2020", "Jain and Wallace 2019": "Jain2019", "Kanev et al. 2021": "Kanev2021",
       "Kurata and Tsukiyama 2022": "Kurata2022", "Li et al. 2020": "Li2020", "Meng et al. 2026": "Meng2026", "Ong et al. 2023": "Ong2023",
       "Serrano and Smith 2019": "Serrano2019", "Tang et al. 2014": "Tang2014", "Tarantino et al. 2026": "Tarantino2026",
       "The UniProt Consortium 2025": "UniProt2025", "van Linden et al. 2014": "vanLinden2014", "Vefghi et al. 2026": "Vefghi2026",
       "Wiegreffe and Pinter 2019": "Wiegreffe2019", "Wu et al. 2025": "Wu2025", "Xiong et al. 2025": "Xiong2025", "Öztürk et al. 2018": "Ozturk2018",
       "Zhao et al. 2022": "Zhao2022"}
ACC = {"Ö": '{\\"O}', "ö": '{\\"o}', "ü": '{\\"u}', "ć": "{\\'c}", "ä": '{\\"a}', "é": "{\\'e}", "ı": "{\\i}", "ş": "{\\c{s}}", "ğ": "{\\u{g}}", "č": "{\\v{c}}", "š": "{\\v{s}}", "ž": "{\\v{z}}"}

def tex(s):
    out = []
    for ch in s:
        if ch in ACC: out.append(ACC[ch])
        elif ord(ch) > 127 and ch not in "–—": raise SystemExit(f"unmapped non-ASCII {ch!r} in bib field: {s[:60]}")
        else: out.append(ch)
    return "".join(out).replace("–", "--").replace("—", "---").replace("&", r"\&").replace("%", r"\%")

def entry(key, rk):
    fn, year, venue, note = B.REFS[rk]
    r = B.load(fn)
    au = r["authors"]
    authors = "{The UniProt Consortium}" if rk.startswith("The UniProt") else " and ".join(tex(a) for a in au)
    f = {"author": authors, "title": "{" + tex(r["title"]) + "}", "year": str(year)}
    ct = (r["container"] or "")
    if venue and ("arXiv preprint" in venue or "bioRxiv" in venue):
        kind = "misc"; f["note"] = tex(venue + (f", doi:{r['DOI']}" if r["DOI"] and "10.48550" not in r["DOI"] else ""))
    elif venue and venue.startswith("Advances in Neural"):
        kind = "inproceedings"; f["booktitle"] = tex(venue)
    elif "Proceedings" in ct:
        kind = "inproceedings"; f["booktitle"] = tex(ct); 
        if r["page"]: f["pages"] = tex(str(r["page"]))
        f["doi"] = r["DOI"]
    else:
        kind = "article"; f["journal"] = tex(ct)
        if r["volume"]: f["volume"] = str(r["volume"])
        if r["page"]: f["pages"] = re.sub(r"(?<=\w)-(?=\w)", "--", tex(str(r["page"])))
        f["doi"] = r["DOI"]
    body = ",\n".join(f"  {k} = {{{v}}}" if k not in ("author", "title") else f"  {k} = {{{v}}}" for k, v in f.items())
    return f"@{kind}{{{key},\n{body}\n}}\n"

bib = ["% Generated by scripts/build_v3_latex.py from paper/citation_verification/ registry records. Do not edit by hand.\n"]
for rk, key in KEY.items():
    bib.append(entry(key, rk))
bib.append("@article{Holm1979,\n  author = {Holm, S.},\n  title = {{A simple sequentially rejective multiple test procedure}},\n  journal = {Scandinavian Journal of Statistics},\n  volume = {6},\n  pages = {65--70},\n  year = {1979},\n  note = {JSTOR 4615733 (no DOI); from paper/references.md}\n}\n")
bib.append("@inproceedings{Sundararajan2017,\n  author = {Sundararajan, M. and Taly, A. and Yan, Q.},\n  title = {{Axiomatic Attribution for Deep Networks}},\n  booktitle = {Proceedings of the 34th International Conference on Machine Learning (PMLR 70)},\n  year = {2017},\n  note = {arXiv:1703.01365; from paper/references.md}\n}\n")
open(os.path.join(OUT, "references.bib"), "w", encoding="utf-8").write("\n".join(bib))

# ---- citation conversion ------------------------------------------------------------------------------------------------------------------
def rx(s): return re.sub(r"\\ ", r"\\s+", re.escape(s))
RAW = lambda t: f"`{t}`{{=latex}}"
CITES = [
 ("(for example GPS-DTI; Xiong et al., 2025)", RAW(r"\citep[for example GPS-DTI;][]{Xiong2025}")),
 ("(Jain and Wallace, 2019; Serrano and Smith, 2019)", RAW(r"\citep{Jain2019,Serrano2019}")),
 ("(Jain and Wallace, 2019; Wiegreffe and Pinter, 2019)", RAW(r"\citep{Jain2019,Wiegreffe2019}")),
 ("(van Linden et al., 2014; Kanev et al., 2021)", RAW(r"\citep{vanLinden2014,Kanev2021}")),
 ("(Sundararajan et al., 2017; 32 steps)", RAW(r"\citep{Sundararajan2017}") + " (32 steps)"),
 ("(Meng et al., 2026, preprint)", RAW(r"\citep[][preprint]{Meng2026}")),
 ("(Wu et al., 2025, preprint)", RAW(r"\citep[][preprint]{Wu2025}")),
 ("(Ong et al., 2023, preprint)", RAW(r"\citep[][preprint]{Ong2023}")),
 ("(Tarantino et al., 2026, preprint)", RAW(r"\citep[][preprint]{Tarantino2026}")),
 ("Vefghi et al. (2026, preprint)", RAW(r"\citet[][preprint]{Vefghi2026}")),
 ("Jacovi and Goldberg (2020)", RAW(r"\citet{Jacovi2020}")),
 ("(InteractBind; Meng et al., 2026)", "(InteractBind; " + RAW(r"\citealp{Meng2026}") + ")"),
]
for text, key in [("Huang et al., 2021", "Huang2021"), ("Zhao et al., 2022", "Zhao2022"), ("Bai et al., 2023", "Bai2023"), ("DeYoung et al., 2020", "DeYoung2020"),
                  ("Li et al., 2020", "Li2020"), ("Kurata and Tsukiyama, 2022", "Kurata2022"), ("Davis et al., 2011", "Davis2011"), ("Tang et al., 2014", "Tang2014"),
                  ("Öztürk et al., 2018", "Ozturk2018"), ("The UniProt Consortium, 2025", "UniProt2025"), ("Holm, 1979", "Holm1979"),
                  ("Adebayo et al., 2018", "Adebayo2018"), ("Wiegreffe and Pinter, 2019", "Wiegreffe2019")]:
    CITES.append((f"({text})", RAW(r"\citep{" + key + "}")))
MATH = {"±": r"$\pm$", "×": r"$\times$", "α": r"$\alpha$", "ρ": r"$\rho$", "≥": r"$\geq$", "÷": r"$\div$", "−": r"$-$"}

def convert_cites(md, label):
    n = 0
    for text, rep in CITES:
        md, k = re.subn(rx(text), lambda m: rep, md)
        n += k
    plain = re.sub(r"`[^`]*`\{=latex\}", "", md)                      # text outside the converted citations
    left = re.findall(r"[A-Za-zÖü]+(?: and [A-Z][a-z]+| et al\.)?,? \(?(?:19|20)\d\d[^)]*\)", plain)
    left += re.findall(r"et al\.,? (?:19|20)\d\d", plain) + re.findall(r"[A-Z][a-z]+, (?:19|20)\d\d\)", plain)
    left = [x for x in left if not x.startswith("(20") and "Wave" not in x]
    if left: raise SystemExit(f"[{label}] unconverted citation-like strings: {left[:5]}")
    return md, n

def pandoc(md, *args):
    return subprocess.run(["pandoc", "-f", "markdown+raw_attribute", *args], input=md, text=True, capture_output=True, check=True).stdout

def fig_block(m):
    name, stem, cap = m.group("lab"), m.group("f"), m.group("cap")
    title, rest = re.match(r"\*\*(.+?)\*\*\s*(.*)", cap, flags=re.S).groups()
    lab = re.sub(r"\W+", "", name).lower()
    cap_tex = pandoc(rest.strip(), "-t", "latex", "--wrap=none").strip()
    shutil.copy(os.path.join(ROOT, "paper", "v2", "figures", stem + ".pdf"), os.path.join(FIG, stem + ".pdf"))
    num = re.sub(r"^(Supplementary )?Figure ", "", title.split(".")[0])
    t = title.split(". ", 1)[1] if ". " in title else title
    return ("```{=latex}\n\\begin{figure}[t]\n\\centering\n\\includegraphics[width=\\linewidth]{figures/" + stem + ".pdf}\n\\caption{\\textbf{" + t.rstrip(".") + ".} " + cap_tex + "}\n\\label{fig:" + lab + "}\n\\end{figure}\n```")

FIGRE = re.compile(r"!\[(?P<lab>[^\]]+)\]\(\.\./v2/figures/(?P<f>[^)]+)\.png\)\n\n(?P<cap>.+?)(?=\n\n|\Z)", re.S)

def prep(md, label):
    md, ncite = convert_cites(md, label)
    for ch, t in MATH.items():
        md = md.replace(ch, RAW(t))
    md, nfig = FIGRE.subn(fig_block, md)
    return md, ncite, nfig

# ---- main manuscript -------------------------------------------------------------------------------------------------------------------------
m = open(os.path.join(V3, "MANUSCRIPT_clean.md"), encoding="utf-8").read()
title = m.split("\n", 1)[0].lstrip("# ").strip()
abs_md = m.split("## Abstract", 1)[1].split("**Mahim Agarwal**", 1)[0].strip()
abs_md = re.sub(r"(https://\S+?)(?=\.\s|\s)", r"<\1>", abs_md.replace("https://github.com/Mahim56207/ColdSite-DTI_New.", "https://github.com/Mahim56207/ColdSite-DTI_New ."), count=1).replace(" .", ".", 1)
body = "# 1 Introduction" + m.split("# 1 Introduction", 1)[1].split("# References", 1)[0]
body, nc, nf = prep(body, "main")
abs_md, nca, _ = prep(abs_md, "abstract")
meta = ("---\ntitle: " + repr(title) + "\nauthor:\n  - Mahim Agarwal\ndate: ''\nbibliography: references\nnatbiboptions: authoryear\nbiblio-style: plainnat\n"
        "geometry: margin=2.5cm\nfontsize: 11pt\nlinkcolor: blue\nurlcolor: blue\nabstract: |\n" + "\n".join("  " + l for l in abs_md.splitlines()) + "\n---\n\n")
subprocess.run(["pandoc", "-f", "markdown+raw_attribute", "-t", "latex", "--wrap=none", "--natbib", "-s", "-o", os.path.join(OUT, "main.tex")], input=meta + body, text=True, check=True)
open(os.path.join(OUT, "manuscript_body.tex"), "w", encoding="utf-8").write(pandoc(body, "-t", "latex", "--wrap=none"))
print(f"main: {nc} citations + {nca} in abstract converted, {nf} figures")

# ---- supplement ------------------------------------------------------------------------------------------------------------------------------
s = open(os.path.join(V3, "SUPPLEMENT_clean.md"), encoding="utf-8").read()
stitle, sbody = s.split("\n", 1)
sbody, nc2, nf2 = prep(sbody, "supplement")
smeta = "---\ntitle: 'Supplementary Information to: " + title.replace("'", "''") + "'\nauthor:\n  - Mahim Agarwal\ndate: ''\nbibliography: references\nnatbiboptions: authoryear\nbiblio-style: plainnat\ngeometry: margin=2cm\nfontsize: 10pt\nheader-includes: |\n  \\renewcommand{\\thefigure}{S\\arabic{figure}}\n---\n\n"
subprocess.run(["pandoc", "-f", "markdown+raw_attribute", "-t", "latex", "--wrap=none", "--natbib", "-s", "-o", os.path.join(OUT, "supplement.tex")], input=smeta + sbody, text=True, check=True)
print(f"supplement: {nc2} citations, {nf2} figures")

with zipfile.ZipFile(os.path.join(V3, "overleaf.zip"), "w", zipfile.ZIP_DEFLATED) as z:
    for dp, _, fs in os.walk(OUT):
        for f in fs:
            p = os.path.join(dp, f); z.write(p, os.path.relpath(p, OUT))
print("wrote", os.path.join(V3, "overleaf.zip"))
