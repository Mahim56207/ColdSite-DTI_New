#!/usr/bin/env python3
"""Build an Overleaf project from the v3 paper: paper/v3_ismb/overleaf/{main.tex, supplement.tex, references.bib, figures/*.pdf} and overleaf.zip.

* references.bib is generated from the saved registry records in paper/citation_verification/ (same records as references.md); nothing is typed by hand
  except the two entries that have no registry record (Holm 1979, Sundararajan 2017), which come from paper/references.md.
* In-text citations of the markdown ("(Huang et al., 2021)") are converted to \\citep/\\citet so BibTeX prints the list; every conversion is counted and
  the script fails if a citation-like string is left unconverted.
* Standard article class + natbib (authoryear, plainnat): the official OUP/Bioinformatics template is NOT verified for the 2027 call, so this is a
  neutral layout whose body text can be pasted into the journal's class later (manuscript_body.tex is written for that).
* This machine has no TeX engine: the output has NOT been compiled here. Compile on Overleaf (pdfLaTeX, default).
"""
