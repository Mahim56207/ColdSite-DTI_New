#!/usr/bin/env python3
"""Build paper/v3_ismb/references.md from the saved registry records in paper/citation_verification/.

No author, title or page is typed here: they come from the Crossref/DataCite records. Only (a) which record belongs to which in-text citation,
(b) the year printed in the text (the volume year, which can differ from the registry's first-online year), and (c) the venue string for
records whose registry entry has none (NeurIPS 2018, arXiv, bioRxiv, JSTOR) are set by hand, each taken from paper/references.md.
Citation style is NOT fixed (the venue template is unverified); this is a working author-year list.
"""
import json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CV = os.path.join(ROOT, "paper", "citation_verification")

def load(name):
    d = json.load(open(os.path.join(CV, name), encoding="utf-8"))
    if "message" in d:                      # raw Crossref response
        m = d["message"]
        au = [(a.get("family", "") + ", " + a.get("given", "")).replace("\xa0", " ") if "family" in a else a.get("name", "") for a in m.get("author", [])]
        return {"authors": au, "title": re.sub(r"<[^>]+>", "", m["title"][0]), "container": (m.get("container-title") or [""])[0],
                "volume": m.get("volume"), "page": m.get("page") or m.get("article-number"), "DOI": m["DOI"]}
    return {"authors": d["authors"], "title": d["title"], "container": d.get("container"), "volume": d.get("volume"),
            "page": d.get("page") or d.get("article_number"), "DOI": d.get("DOI") or d.get("doi")}

def initials(given):
    parts = re.split(r"[\s]+", given.strip())
    out = []
    for p in parts:
        out.append("-".join(x[0] + "." for x in p.split("-") if x))
    return " ".join(out)

def fmt_author(a):
    if ", " not in a:
        return a
    fam, giv = a.split(", ", 1)
    return f"{fam}, {initials(giv)}"

# key (as cited in the text) -> (record file, year in text, venue override or None, extra note)
REFS = {
 "Adebayo et al. 2018": ("Adebayo2018.json", 2018, "Advances in Neural Information Processing Systems (NeurIPS) 2018; arXiv:1810.03292", ""),
 "Bai et al. 2023": ("Bai2023_DrugBAN.json", 2023, None, ""),
 "Davis et al. 2011": ("crossref_10.1038_nbt.1990.json", 2011, None, ""),
 "DeYoung et al. 2020": ("DeYoung2020_ERASER.json", 2020, None, ""),
 "Huang et al. 2021": ("crossref_10.1093_bioinformatics_btaa880.json", 2021, None, ""),
 "Jacovi and Goldberg 2020": ("JacoviGoldberg2020.json", 2020, None, ""),
 "Jain and Wallace 2019": ("JainWallace2019.json", 2019, None, ""),
 "Kanev et al. 2021": ("crossref_10.1093_nar_gkaa895.json", 2021, None, ""),
 "Kurata and Tsukiyama 2022": ("Kurata2022_ICAN.json", 2022, None, ""),
 "Li et al. 2020": ("Li2020_MONN.json", 2020, None, ""),
 "Meng et al. 2026": ("InteractBind_2605.24045.json", 2026, "arXiv preprint, arXiv:2605.24045", "preprint"),
 "Ong et al. 2023": ("bioRxiv2023_556234.json", 2023, "bioRxiv preprint", "preprint"),
 "Serrano and Smith 2019": ("crossref_10.18653_v1_P19-1282.json", 2019, None, ""),
 "Tang et al. 2014": ("crossref_10.1021_ci400709d.json", 2014, None, ""),
 "Tarantino et al. 2026": ("ISAAC_2605.02962.json", 2026, "arXiv preprint, arXiv:2605.02962", "preprint"),
 "The UniProt Consortium 2025": ("crossref_10.1093_nar_gkae1010.json", 2025, None, ""),
 "van Linden et al. 2014": ("crossref_10.1021_jm400378w.json", 2014, None, ""),
 "Vefghi et al. 2026": ("Vefghi2026_2606.14245.json", 2026, "arXiv preprint, arXiv:2606.14245", "preprint"),
 "Wiegreffe and Pinter 2019": ("WiegreffePinter2019.json", 2019, None, ""),
 "Zhao et al. 2022": ("crossref_10.1093_bioinformatics_btab715.json", 2022, None, ""),
 "Wu et al. 2025": ("DAVIScomplete_2512.00708.json", 2025, "arXiv preprint, arXiv:2512.00708", "preprint"),
 "Xiong et al. 2025": ("crossref_10.1186_s12915-025-02456-9.json", 2025, None, ""),
 "Öztürk et al. 2018": ("crossref_10.1093_bioinformatics_bty593.json", 2018, None, ""),
}

lines = ["# References (v3, working list)", "",
 "<!-- Generated by scripts/build_v3_references.py from the saved registry records in paper/citation_verification/ -- no author, title or page typed by hand. "
 "Citation style is NOT fixed (the venue template is unverified): this is a neutral author-year list; reformat when the template is known. "
 "The year printed is the volume year used in the text; the registry's first-online year can differ (e.g. Huang 2021, Zhao 2022, Kanev 2021, UniProt 2025). "
 "Preprints are marked. Holm 1979 has no DOI (JSTOR 4615733) and is listed from paper/references.md. -->", ""]
entries = []
for key, (fn, year, venue, note) in REFS.items():
    r = load(fn)
    au = r["authors"]
    if key.startswith("The UniProt"):
        auth = "The UniProt Consortium"
    else:
        auth = ", ".join(fmt_author(a) for a in au)
    v = venue or ((r["container"] or "") + (f" {r['volume']}" if r["volume"] else "") + (f", {r['page']}" if r["page"] else ""))
    tail = f" doi:{r['DOI']}" if r["DOI"] and "10.48550" not in r["DOI"] else ""
    title = r['title'].rstrip('.')
    title = title if title.endswith('?') else title + '.'
    entries.append((key, f"{auth} ({year}) {title} {v}.{tail}" + (" **[preprint]**" if note else "")))
entries.append(("Holm 1979", "Holm, S. (1979) A simple sequentially rejective multiple test procedure. Scandinavian Journal of Statistics 6, 65–70. JSTOR 4615733."))
entries.append(("Sundararajan et al. 2017 (Supplement)", "Sundararajan, M., Taly, A., Yan, Q. (2017) Axiomatic Attribution for Deep Networks. Proceedings of the 34th International Conference on Machine Learning (PMLR 70); arXiv:1703.01365."))
for key, text in sorted(entries, key=lambda e: e[0].lower().replace("ö", "o").replace("the ", "")):
    lines.append(f"* {text}")
open(os.path.join(ROOT, "paper", "v3_ismb", "references.md"), "w", encoding="utf-8").write("\n".join(lines) + "\n")
print(len(entries), "entries")
